/**
 * SHA-256 of each Check 1-7 block as it stood at the commit T-43 branched from
 * (dc9a4c12, measured 2026-09-02). Frozen here rather than read from HEAD every
 * run for one reason: the moment the commit that lands T-43 is made, HEAD's
 * doctor.md contains Check 8 and Check 9, and a gate that compares against HEAD
 * would then be comparing this change against itself. A frozen digest keeps
 * asserting the same thing after the commit as before it.
 *
 * Changing a value here is only correct when Check 1-7 prose is DELIBERATELY
 * edited. Refreshing one to make a red test green is how a ratchet destroys its
 * own reference.
 *
 * Check 7 was re-frozen ONCE, on 2026-09-03, for a deliberate edit that had
 * nothing to do with T-43: the decision-event store moved from
 * `<pluginRoot>/runtime/decisions/` to `<projectRoot>/.artibot/runtime/decisions/`
 * (`lib/observability/decision-events.js#getDecisionStoreDir`), and Check 7 is
 * that store's only reader. Its text had to follow, because the two stores no
 * longer share a root and S6's stated rationale ("both under the same resolved
 * root") had become false. Checks 1-6 are untouched and still carry their
 * dc9a4c12 digests, which is what keeps this refresh auditable: a refresh that
 * moved all seven would prove nothing.
 *   66d45dd3e6cc4812 -> 68a73087845aa9cd
 */
const CHECK_1_7_SHA256 = Object.freeze({
  'Check 1': '68a7994da5db8345',
  'Check 2': 'abb2dcdb15ee2345',
  'Check 3': '13cf1d3e560e5b64',
  'Check 4': 'b48ec269f024a6d3',
  'Check 5': '76b677614892ac3c',
  'Check 6': '889cb2c477eae694',
  // Re-frozen 2026-09-03 (store path move). See the note above.
  'Check 7': '68a73087845aa9cd',
});

// Truncated to 16 hex characters, the same shape `lib/core/skill-hash.js` uses
// for its own content digests. 64 bits is far past collision reach for seven
// fixed strings, and the full digest reads to a secret scanner as a credential.
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);

describe('Checks 1-7 were not touched', () => {
  const current = checkSections(CURRENT);

  it('still carries exactly seven original sections plus the two new ones', () => {
    expect([...current.keys()]).toHaveLength(9);
  });

  it.each([1, 2, 3, 4, 5, 6, 7])('keeps Check %i byte-identical to the frozen baseline', (n) => {
    const key = `Check ${n}`;
    expect(current.get(key)).toBeTypeOf('string');
    expect(sha(current.get(key))).toBe(CHECK_1_7_SHA256[key]);
  });

  it('keeps the seven existing output-format lines byte-identical', () => {
    for (let n = 1; n <= 7; n += 1) {
      const line = HEAD.split('\n').find((l) => l.startsWith(`[check-${n}-icon]`));
      expect(line).toBeTypeOf('string');
      expect(CURRENT).toContain(line);
    }
  });
});

describe('the frozen baseline still matches git, while HEAD predates T-43', () => {
  // A second, independent witness for the pre-commit window. Once T-43 lands,
  // HEAD carries Check 8 and this comparison would grade the change against
  // itself, so it stands down and says so rather than asserting something
  // weaker under the same name.
  const headHasNewChecks = HEAD.includes('### Check 8');
  const head = checkSections(HEAD);

  it.skipIf(headHasNewChecks)('reads seven check sections at HEAD', () => {
    expect([...head.keys()]).toHaveLength(7);
  });

  it.skipIf(headHasNewChecks)('agrees with the frozen digests', () => {
    for (const [key, digest] of Object.entries(CHECK_1_7_SHA256)) {
      expect(sha(head.get(key))).toBe(digest);
    }
  });
});
