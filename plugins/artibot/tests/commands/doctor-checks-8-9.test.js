describe('checkLedgerStateParity — the journal still reproduces state.yaml', () => {
  it('passes when the fold reproduces the projection and every version is paired', () => {
    const result = checkLedgerStateParity({
      events: [stateUpdated(1)],
      journal: [missionRecord(1, MISSION)],
      projection: EXPECTED_PROJECTION,
    });
    expect(result.status).toBe(CheckStatus.PASS);
    expect(result.findings).toEqual([]);
  });

  it('fails when the projection on disk disagrees with the rebuild', () => {
    const drifted = {
      ...EXPECTED_PROJECTION,
      active_missions: { [MID]: { ...EXPECTED_PROJECTION.active_missions[MID], status: 'completed' } },
    };
    const result = checkLedgerStateParity({
      events: [stateUpdated(1)],
      journal: [missionRecord(1, MISSION)],
      projection: drifted,
    });
    expect(result.status).toBe(CheckStatus.FAIL);
    expect(codes(result)).toContain('projection-drift');
    expect(result.findings[0].comparison).toBe('structural');
  });

  it('compares raw text byte for byte, which is the design rule', () => {
    const result = checkLedgerStateParity({
      events: [stateUpdated(1)],
      journal: [missionRecord(1, MISSION)],
      projection: 'project: artibot\n',
    });
    expect(result.status).toBe(CheckStatus.FAIL);
    expect(result.findings[0].comparison).toBe('bytes');
  });

  it('fails on a store version with no paired event — the invariant broken', () => {
    const result = checkLedgerStateParity({
      events: [],
      journal: [missionRecord(1, MISSION)],
      projection: EXPECTED_PROJECTION,
    });
    expect(result.status).toBe(CheckStatus.FAIL);
    expect(codes(result)).toContain('ledger-subset-violation');
  });

  it('only warns when the store is behind the ledger — the invariant holds', () => {
    const result = checkLedgerStateParity({
      events: [stateUpdated(1), stateUpdated(2)],
      journal: [missionRecord(1, MISSION)],
      projection: EXPECTED_PROJECTION,
    });
    expect(result.status).toBe(CheckStatus.WARN);
    expect(codes(result)).toContain('store-behind-ledger');
    expect(codes(result)).not.toContain('ledger-subset-violation');
  });

  it.each([
    ['events', { journal: [], projection: EXPECTED_PROJECTION }, 'events (ledger)'],
    ['journal', { events: [], projection: EXPECTED_PROJECTION }, 'journal (store)'],
    ['projection', { events: [], journal: [] }, 'projection (state.yaml)'],
  ])('reports unmeasured, not pass, when %s was not read', (_name, input, absent) => {
    const result = checkLedgerStateParity(input);
    expect(result.status).toBe(CheckStatus.UNMEASURED);
    expect(result.findings[0].absent).toContain(absent);
  });

  it('distinguishes an empty-but-read store from a store never read', () => {
    const read = checkLedgerStateParity({
      events: [], journal: [], projection: { project: 'artibot', state_version: 0, active_missions: {} },
    });
    expect(read.status).toBe(CheckStatus.PASS);
    expect(checkLedgerStateParity({}).status).toBe(CheckStatus.UNMEASURED);
  });
});

