/**
 * Split a command document into its `### Check N` blocks, each running to the
 * next heading of level 2 or 3.
 *
 * @param {string} md - Document text, newline-normalised.
 * @returns {Map<string, string>} Check label to block text.
 */
function checkSections(md) {
  const headings = [...md.matchAll(/^#{2,3} .*$/gm)];
  const out = new Map();
  headings.forEach((h, i) => {
    const label = h[0].match(/^### (Check \d+)/);
    if (label === null) return;
    const end = i + 1 < headings.length ? headings[i + 1].index : md.length;
    out.set(label[1], md.slice(h.index, end));
  });
  return out;
}

