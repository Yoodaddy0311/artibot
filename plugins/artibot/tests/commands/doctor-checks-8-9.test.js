/**
 * T-43 — `/doctor` Check 8 and Check 9.
 *
 * ── What these tests DO establish ─────────────────────────────────────────
 * That the pure judgement functions return the verdict the design specifies
 * for a hand-built input, that `unmeasured` is returned wherever an input was
 * not supplied, that the ten Check 9 items match Hardening §32 line for line,
 * and that adding the two sections left Checks 1-7 of `commands/doctor.md`
 * byte-identical to HEAD.
 *
 * ── What they CANNOT establish (§9 — state it next to the gate) ───────────
 * - **Anything about a live ledger.** Every fixture here is hand-built and
 *   tiny. Zero real `ledger.jsonl` records were read, so nothing here says the
 *   check behaves the same against a production-sized store, and the
 *   fixture-size trap applies in full: these inputs are single-digit records
 *   where a real store is unbounded.
 * - **That `/doctor` was ever run.** `commands/doctor.md` is a markdown command
 *   read by the model, not code this suite can execute. These tests assert the
 *   document says what it should and that the functions it names behave; they
 *   do NOT assert that any run of `/doctor` calls them, and no such run has
 *   been observed.
 * - **That the caller wires the inputs correctly.** The functions are pure and
 *   the reading half lives in the command prose. A command that reads the wrong
 *   file would still produce green tests here.
 * - **That the ten items are individually correct against a real project.**
 *   Each item is exercised by one passing and one failing fixture, which fixes
 *   the contract, not the field accuracy.
 */

