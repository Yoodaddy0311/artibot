#!/usr/bin/env node
/**
 * Generate `plugins/artibot/agents/INDEX.md` from the self-registering
 * agent registry. Phase 2 WS-B.4 auto-built index.
 *
 * Usage:
 *   node plugins/artibot/scripts/generate-agent-index.js
 *
 * Re-run after agent frontmatter changes. Always exits 0 (soft failure
 * via stderr) so pre-commit / CI wrapping can't wedge on index rebuilds.
 *
 * @module scripts/generate-agent-index
 */

import path from 'node:path';
import { atomicWriteSync, getPluginRoot, toFileUrl } from './utils/index.js';

const LIFECYCLE_ORDER = ['build', 'review', 'verify', 'operate', 'marketing', 'null'];

/**
 * Dynamically import the agent registry using a Korean-path-safe URL.
 *
 * @returns {Promise<typeof import('../lib/core/agent-registry.js')>}
 */
async function importRegistry() {
  const modPath = path.join(getPluginRoot(), 'lib', 'core', 'agent-registry.js');
  return import(toFileUrl(modPath));
}

/**
 * Group agents by lifecycle (null-lifecycle bucketed under 'null').
 *
 * @param {import('../lib/core/agent-registry.js').AgentEntry[]} agents
 * @returns {Map<string, import('../lib/core/agent-registry.js').AgentEntry[]>}
 */
function groupByLifecycle(agents) {
  const groups = new Map();
  for (const a of agents) {
    const key = a.lifecycle === null ? 'null' : a.lifecycle || 'null';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(a);
  }
  for (const list of groups.values()) list.sort((x, y) => x.name.localeCompare(y.name));
  return groups;
}

/**
 * Format a single GFM table row for an agent entry.
 *
 * @param {import('../lib/core/agent-registry.js').AgentEntry} a
 * @param {boolean} withLifecycle
 * @param {number} [index]
 * @returns {string}
 */
function formatRow(a, withLifecycle, index) {
  const caps = (a.capabilities || []).join(', ') || '-';
  const model = a.model || '-';
  const lc = a.lifecycle === null ? 'null' : a.lifecycle || 'null';
  if (withLifecycle) {
    return `| ${index} | ${a.name} | ${lc} | ${caps} | ${model} |`;
  }
  return `| ${a.name} | ${caps} | ${model} |`;
}

/**
 * Render the "By Lifecycle" sections in canonical order.
 *
 * @param {Map<string, import('../lib/core/agent-registry.js').AgentEntry[]>} groups
 * @returns {string}
 */
function renderLifecycleSections(groups) {
  const out = ['## By Lifecycle', ''];
  const seen = new Set();
  const order = [...LIFECYCLE_ORDER, ...[...groups.keys()].filter((k) => !LIFECYCLE_ORDER.includes(k))];
  for (const key of order) {
    if (seen.has(key)) continue;
    seen.add(key);
    const list = groups.get(key);
    if (!list || list.length === 0) continue;
    const title = key.charAt(0).toUpperCase() + key.slice(1);
    out.push(`### ${title} (${list.length} agents)`);
    out.push('| Agent | Capabilities | Model |');
    out.push('|-------|-------------|-------|');
    for (const a of list) out.push(formatRow(a, false));
    out.push('');
  }
  return out.join('\n');
}

/**
 * Render the alphabetical "All Agents" table.
 *
 * @param {import('../lib/core/agent-registry.js').AgentEntry[]} agents
 * @returns {string}
 */
function renderAllAgents(agents) {
  const sorted = [...agents].sort((x, y) => x.name.localeCompare(y.name));
  const out = ['## All Agents (alphabetical)', ''];
  out.push('| # | Agent | Lifecycle | Capabilities | Model |');
  out.push('|---|-------|-----------|-------------|-------|');
  sorted.forEach((a, idx) => out.push(formatRow(a, true, idx + 1)));
  out.push('');
  return out.join('\n');
}

/**
 * Build the complete INDEX.md document text.
 *
 * @param {import('../lib/core/agent-registry.js').AgentEntry[]} agents
 * @returns {string}
 */
function renderIndex(agents) {
  const groups = groupByLifecycle(agents);
  const header = [
    '# Artibot Agent Index',
    '',
    '> Auto-generated by `scripts/generate-agent-index.js`. Do not edit by hand.',
    '> Re-run after agent frontmatter changes.',
    `> Total agents: ${agents.length} | Generated: ${new Date().toISOString()}`,
    '',
  ].join('\n');
  return `${header}\n${renderLifecycleSections(groups)}\n${renderAllAgents(agents)}`;
}

/**
 * Main entrypoint. Soft-fails with stderr + exit 0.
 *
 * @returns {Promise<void>}
 */
async function main() {
  try {
    const { loadAgentRegistry } = await importRegistry();
    const map = await loadAgentRegistry();
    const agents = [...map.values()];
    const doc = renderIndex(agents);
    const outPath = path.join(getPluginRoot(), 'agents', 'INDEX.md');
    atomicWriteSync(outPath, doc);
    process.stdout.write(`[generate-agent-index] wrote ${agents.length} agents to ${outPath}\n`);
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    process.stderr.write(`[generate-agent-index] failed: ${msg}\n`);
  }
  process.exit(0);
}

main();
