#!/usr/bin/env node
/**
 * Git Autopilot — UserPromptSubmit hook.
 * Triggers a WIP (work-in-progress) auto-save commit when the configurable
 * interval has elapsed since the last save. Transparent to the user —
 * does not modify the prompt (no stdout write).
 * @module scripts/hooks/git-autopilot-save
 */

import { existsSync, readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { atomicWriteSync, parseJSON, readStdin, resolveConfigPath } from '../utils/index.js';
import { createErrorHandler } from '../../lib/core/hook-utils.js';
import { isAutopilotAllowed } from '../../lib/autopilot/repo-identity.js';
import { gitPath } from '../../lib/git/git-dir.js';
import { isMainEntry } from './_main-entry.js';

/**
 * Read `git.autopilot.bypassPreCommitHooks` from artibot.config.json.
 * Defaults to false (honour pre-commit hooks). v4.7.2 (issue-scanner W4 P1-3):
 * the previous unconditional `--no-verify` violated CLAUDE.md Git Safety
 * Protocol — opt-in is now required.
 * @returns {boolean}
 */
function readArtibotBypassPreCommitHooks() {
  try {
    const cfg = JSON.parse(readFileSync(resolveConfigPath('artibot.config.json'), 'utf-8'));
    return cfg?.git?.autopilot?.bypassPreCommitHooks === true;
  } catch {
    return false;
  }
}

/**
 * Read `git.autopilot.commitStrategy` from artibot.config.json.
 * Values: "semantic" (stash checkpoint, default), "interval" (legacy WIP
 * commits), "none" (skip all auto-saves).
 * @returns {"semantic"|"interval"|"none"}
 */
function readCommitStrategy() {
  try {
    const cfg = JSON.parse(readFileSync(resolveConfigPath('artibot.config.json'), 'utf-8'));
    const strategy = cfg?.git?.autopilot?.commitStrategy;
    if (strategy === 'interval' || strategy === 'none') return strategy;
    return 'semantic';
  } catch {
    return 'semantic';
  }
}

// -------------------------------------------------------------------------
// Helpers
// -------------------------------------------------------------------------

/**
 * Get the repo root via git rev-parse.
 * @returns {string|null}
 */
function getRepoRoot() {
  try {
    return execSync('git rev-parse --show-toplevel', {
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 2000,
      windowsHide: true,
    }).trim();
  } catch {
    return null;
  }
}

/**
 * Load .git/autopilot.json. Returns null if disabled or missing.
 * @param {string} repoRoot
 * @returns {object|null}
 */
function loadConfig(repoRoot) {
  const configPath = gitPath(repoRoot, 'autopilot.json');
  if (!existsSync(configPath)) return null;
  try {
    const config = JSON.parse(readFileSync(configPath, 'utf-8'));
    return config.enabled === false ? null : config;
  } catch {
    return null;
  }
}

/**
 * Load the WIP state file (.git/autopilot-state.json).
 * @param {string} repoRoot
 * @returns {{ lastWipAt: string|null }}
 */
function loadState(repoRoot) {
  const statePath = gitPath(repoRoot, 'autopilot-state.json');
  if (!existsSync(statePath)) return { lastWipAt: null };
  try {
    return JSON.parse(readFileSync(statePath, 'utf-8'));
  } catch {
    return { lastWipAt: null };
  }
}

/**
 * Save the WIP state with updated timestamp.
 * @param {string} repoRoot
 * @param {object} state
 */
function saveState(repoRoot, state) {
  const statePath = gitPath(repoRoot, 'autopilot-state.json');
  atomicWriteSync(statePath, state);
}

/**
 * Path patterns matching auto-generated artifacts that should NOT, on their
 * own, trigger a WIP commit. Reason: learning subsystems mutate these files
 * every session (telemetry, learned rules, GRPO output). When the user makes
 * no real edits but a 30-min interval elapses, a WIP commit that contains
 * ONLY these auto-mutations creates "ahead of origin" noise that masks the
 * real upstream state across machines.
 *
 * The files are still tracked and still get committed when a WIP fires
 * (because real edits also exist) — they just no longer trigger WIP alone.
 */
const AUTO_GENERATED_PATTERNS = [
  /\/auto-learned-rules\.json$/,
  /\/lessons-learned\.json$/,
  /\/runtime\//,
];

function isAutoGenerated(filePath) {
  return AUTO_GENERATED_PATTERNS.some((re) => re.test(filePath));
}

/**
 * Check whether the workspace has any changes worth a WIP commit. Returns
 * false when the only dirty files are auto-generated artifacts — preserves
 * cross-machine version coherence by skipping no-op WIP commits.
 *
 * @param {string} cwd
 * @returns {boolean}
 */
function hasMeaningfulChanges(cwd) {
  try {
    const status = execSync('git status --porcelain', {
      cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 2000,
      windowsHide: true,
    });
    const lines = status.trim().split('\n').filter(Boolean);
    if (lines.length === 0) return false;
    // `git status --porcelain` format: "XY␣filename" (X=staged, Y=unstaged).
    // Renames use "XY old -> new" — take the part after "-> " when present.
    return lines.some((line) => {
      const rest = line.slice(3).trim();
      const arrow = rest.lastIndexOf(' -> ');
      const file = arrow >= 0 ? rest.slice(arrow + 4) : rest;
      return !isAutoGenerated(file);
    });
  } catch {
    return false;
  }
}

/**
 * Stage all changes and create a WIP commit.
 *
 * v4.7.2 (issue-scanner W4 P1-3): pre-commit hooks are honored by default.
 * Set `git.autopilot.bypassPreCommitHooks: true` in artibot.config.json to
 * restore the pre-v4.7.2 behavior of passing `--no-verify`. The default
 * (`false`) lets secret-scan / lint / test gates fail the auto-save commit
 * instead of silently committing through them — see CLAUDE.md Git Safety
 * Protocol.
 *
 * @param {string} cwd
 * @param {{ bypassPreCommitHooks?: boolean }} [opts]
 * @returns {boolean} true if commit succeeded
 */
function createWipCommit(cwd, opts = {}) {
  try {
    execSync('git add -A', { cwd, stdio: 'ignore', timeout: 2000, windowsHide: true });
    const timestamp = new Date().toISOString().replace('T', ' ').slice(0, 19);
    const bypass = opts.bypassPreCommitHooks === true;
    const noVerify = bypass ? ' --no-verify' : '';
    execSync(`git commit -m "wip: artibot auto-save [${timestamp}]"${noVerify}`, {
      cwd,
      stdio: 'ignore',
      timeout: 5000,
      windowsHide: true,
    });
    return true;
  } catch {
    return false;
  }
}

/**
 * Create a stash-based checkpoint. The stash entry persists in the reflog for
 * crash recovery.
 *
 * NON-DESTRUCTIVE by design: uses `git stash create` + `git stash store`, which
 * build and record a stash commit object WITHOUT ever touching the working tree.
 *
 * History: the previous implementation used `git stash push --include-untracked`
 * followed by `git stash pop`. `git stash push` internally hard-resets the
 * working tree to HEAD (visible in the reflog as "reset: moving to HEAD") before
 * popping it back. That left a window where the tree was at HEAD and a concurrent
 * teammate's uncommitted edits lived only in the stash — and on a `pop` conflict
 * (or two interleaved checkpoint cycles) the edits silently vanished from the
 * working tree. `create` + `store` removes that entire failure class: the tree is
 * never reset, so concurrent agent work on disk is never disturbed.
 *
 * Trade-off: `git stash create` snapshots tracked changes only (not untracked
 * files). That is acceptable here — untracked files are never removed from disk
 * (the tree is untouched), so they stay safe; full-capture recovery is the job of
 * the "interval" WIP-commit strategy (`git add -A`), not this checkpoint.
 *
 * @param {string} cwd
 * @param {{ phase?: string }} [opts]
 * @returns {boolean} true if a checkpoint was created
 */
function createStashCheckpoint(cwd, opts = {}) {
  const phase = opts.phase ?? 'unknown';
  const timestamp = new Date().toISOString().replace('T', ' ').slice(0, 19);
  const label = `artibot-checkpoint-${phase}-${timestamp}`;
  let sha;
  try {
    // `git stash create` builds a stash commit from the current tracked changes
    // and prints its SHA WITHOUT modifying the working tree. Empty output means
    // there was nothing to checkpoint (clean tree).
    sha = execSync('git stash create', {
      cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 5000,
      windowsHide: true,
    }).trim();
  } catch {
    // create can fail if git is not initialized or on a bare repo.
    return false;
  }

  if (!sha) {
    // Nothing to checkpoint — working tree had no tracked changes.
    return false;
  }

  // Record the snapshot in the stash reflog for crash recovery. `store` does not
  // touch the working tree either.
  try {
    execSync(`git stash store -m "${label}" ${sha}`, {
      cwd,
      stdio: 'ignore',
      timeout: 2000,
      windowsHide: true,
    });
  } catch {
    // Snapshot object still exists in the object DB even if store fails; the
    // working tree is unaffected, so this is non-fatal.
    return false;
  }

  return true;
}

/**
 * Resolve the commit a stash index currently points at.
 *
 * Uses `execSync` like every other git call in this module: `idx` is a number
 * parsed out of `git stash list` output, so there is nothing to inject, and the
 * module's tests drive it through a single `execSync` seam.
 *
 * @param {string} cwd
 * @param {number} idx
 * @returns {string|null} SHA, or null when the index no longer resolves.
 */
function stashShaAt(cwd, idx) {
  try {
    const out = execSync(`git rev-parse stash@{${idx}}`, {
      cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 2000,
      windowsHide: true,
    });
    return String(out).trim() || null;
  } catch {
    return null;
  }
}

/**
 * Remove old artibot checkpoint stashes beyond the retention limit.
 * Keeps the most recent entries and drops the oldest.
 *
 * `refs/stash` is shared across every worktree of a repository — measured
 * 2026-08-26: a stash pushed from a linked worktree renumbers `stash@{n}` for
 * the main checkout too, so the entry that was `stash@{0}` at list time becomes
 * `stash@{1}` mid-loop. An index captured from `git stash list` is therefore a
 * position, not an identity, and dropping by that stale position destroys
 * somebody else's stash. Every drop re-resolves the index first; on a mismatch
 * it refuses that drop and abandons the rest of the loop. Drops already made
 * under a still-valid pin stay — they were correct — so a cleanup can end having
 * removed some of its targets and not the others. The guarantee is not "all or
 * nothing"; it is that the wrong stash is never dropped. Falling behind on
 * retention is recoverable, dropping somebody else's stash is not.
 *
 * Exported for `tests/firewall/stash-ref-isolation.test.js`: the shared-ref
 * hazard cannot be exercised through `main()` without driving a whole hook
 * event, and a test that re-implemented this loop would be testing its own copy.
 *
 * `opts.stashShaAt` is a seam, not a feature: the guard only fires when the
 * stash ref moves BETWEEN the collection pass and the drop pass of one call,
 * and no test can wedge a real `git stash push` into that window. Injecting the
 * resolver lets a test answer one SHA while pinning and a different one at
 * re-check, which is exactly what a concurrent push looks like from in here.
 * Production passes nothing and runs the real resolver.
 *
 * @param {string} cwd
 * @param {number} maxStashes maximum checkpoint stashes to retain (default 10)
 * @param {{ stashShaAt?: (cwd: string, idx: number) => string|null }} [opts]
 */
export function cleanupOldStashes(cwd, maxStashes = 10, opts = {}) {
  const resolveSha = opts.stashShaAt ?? stashShaAt;
  try {
    const raw = execSync('git stash list', {
      cwd,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 2000,
      windowsHide: true,
    });
    const lines = raw.trim().split('\n').filter(Boolean);
    // Collect indices of artibot checkpoint entries (in reflog order, 0 = newest),
    // pinning each to the commit it resolved to at list time.
    const checkpoints = [];
    for (const line of lines) {
      if (!line.includes('artibot-checkpoint-')) continue;
      const match = line.match(/^stash@\{(\d+)\}/);
      if (!match) continue;
      const idx = Number(match[1]);
      const sha = resolveSha(cwd, idx);
      if (sha) checkpoints.push({ idx, sha });
    }
    if (checkpoints.length <= maxStashes) return;

    // Drop oldest first. Dropping shifts indices, so we process from highest
    // index to lowest to avoid invalidation.
    const toDrop = checkpoints.slice(maxStashes).sort((a, b) => b.idx - a.idx);
    for (const { idx, sha } of toDrop) {
      if (resolveSha(cwd, idx) !== sha) return;
      execSync(`git stash drop stash@{${idx}}`, {
        cwd,
        stdio: 'ignore',
        timeout: 2000,
        windowsHide: true,
      });
    }
  } catch {
    // Non-critical — silently ignore cleanup failures.
  }
}

// -------------------------------------------------------------------------
// Main
// -------------------------------------------------------------------------

export async function main() {
  const raw = await readStdin();
  const hookData = parseJSON(raw) ?? {};

  const repoRoot = getRepoRoot();
  if (!repoRoot) return;

  // Capture-only gate: skip all git writes for repos outside the allowlist.
  // Learning subsystems (lifelong-learner / GRPO / swarm) are unaffected.
  if (!isAutopilotAllowed(repoRoot)) return;

  const config = loadConfig(repoRoot);
  if (!config) return;

  const strategy = config.commitStrategy ?? readCommitStrategy();

  // commitStrategy: "none" — disable all auto-save activity.
  if (strategy === 'none') return;

  // Default interval depends on strategy:
  //   "semantic" (stash) → 30 min — lightweight, no history pollution.
  //   "interval" (WIP commit) → 120 min — heavier, legacy crash safety.
  const defaultInterval = strategy === 'semantic' ? 30 : 120;
  const intervalMs = (config.wipIntervalMinutes ?? defaultInterval) * 60 * 1000;
  const state = loadState(repoRoot);
  const now = Date.now();
  const lastWip = state.lastWipAt ? new Date(state.lastWipAt).getTime() : 0;

  if (now - lastWip < intervalMs) return; // Not yet time

  if (!hasMeaningfulChanges(repoRoot)) {
    // Only auto-generated files dirty (or fully clean) — skip save.
    // Update timestamp to avoid rechecking immediately.
    saveState(repoRoot, { ...state, lastWipAt: new Date(now).toISOString() });
    return;
  }

  const newTimestamp = new Date(now).toISOString();

  if (strategy === 'semantic') {
    // Stash-based checkpoint — no git history pollution.
    const phase = config.currentPhase ?? 'autopilot';
    const saved = createStashCheckpoint(repoRoot, { phase });
    saveState(repoRoot, { ...state, lastWipAt: newTimestamp });

    if (saved) {
      cleanupOldStashes(repoRoot, config.maxStashes ?? 10);
      process.stderr.write(
        `[artibot:git-autopilot-save] stash checkpoint created at ${newTimestamp}\n`,
      );
    } else {
      process.stderr.write(
        '[artibot:git-autopilot-save] stash checkpoint skipped — no changes or git error\n',
      );
    }
  } else {
    // strategy === "interval" — legacy WIP commit behavior.
    const bypassPreCommitHooks = config?.bypassPreCommitHooks === true
      || readArtibotBypassPreCommitHooks();
    const saved = createWipCommit(repoRoot, { bypassPreCommitHooks });
    saveState(repoRoot, { ...state, lastWipAt: newTimestamp });

    if (saved) {
      process.stderr.write(`[artibot:git-autopilot-save] WIP auto-saved at ${newTimestamp}\n`);
    } else {
      process.stderr.write('[artibot:git-autopilot-save] WIP commit failed — check git status\n');
    }
  }

  // Do not write to stdout — pass prompt through unchanged
  void hookData;
}

// Direct-run guard: importing this module (tests) must not execute a real
// auto-save — main() blocks on stdin and, past its gates, writes git state
// (`git add -A`, WIP commit, `git stash create`/`store`). Production is
// unaffected: `_userprompt-dispatcher.js` spawns this file as argv[1].
if (isMainEntry(import.meta.url)) {
  main().catch(createErrorHandler('git-autopilot-save', { exit: true }));
}
